const LOCALES = { en: "en-US", ko: "ko-KR" };
const STORAGE_KEY = "agentville-language";
export const LANGUAGES = Object.keys(STRINGS);

function initialLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (Object.hasOwn(STRINGS, saved)) return saved;
  } catch {}
  return String(navigator.language || "").toLowerCase().startsWith("ko") ? "ko" : "en";
}
let language = initialLanguage();

export function t(key, params = {}) {
  const template = STRINGS[language][key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match);
}
export function currentLanguage() { return language; }
export function locale() { return LOCALES[language]; }
export function setLanguage(next) {
  if (!Object.hasOwn(STRINGS, next)) return;
  language = next;
  try { localStorage.setItem(STORAGE_KEY, next); } catch {}
}
// Static markup names its strings with data-i18n (text) and data-i18n-attr ("attribute=key,attribute=key").
export function translateDocument(root = document) {
  document.documentElement.lang = language;
  document.title = t("doc.title");
  document.querySelector('meta[name="description"]')?.setAttribute("content", t("doc.description"));
  root.querySelectorAll("[data-i18n]").forEach((node) => { node.textContent = t(node.dataset.i18n); });
  root.querySelectorAll("[data-i18n-attr]").forEach((node) => {
    for (const pair of node.dataset.i18nAttr.split(",")) {
      const [attribute, key] = pair.split("=");
      node.setAttribute(attribute.trim(), t(key.trim()));
    }
  });
}
